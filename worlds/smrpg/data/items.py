class ItemData:
    name: str
    remake_name: str
    game_id: int

    def __init__(self, name: str, game_id: int, remake_name: str = None):
        self.name = name
        self.game_id = game_id
        self.remake_name = remake_name

    def __repr__(self):
        if self.remake_name == 'None':
            return f"{self.name} ({hex(self.game_id)})"
        else:
            return f"{self.name}/{self.remake_name} ({hex(self.game_id)})"

